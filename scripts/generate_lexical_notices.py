"""Collect notices for the lexical crate's locked normal dependency closure.

Run after changing lexical/Cargo.lock. Cargo downloads the exact locked sources;
upstream notices missing from crate archives are retained in LICENSES/lex/.
"""

import argparse
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CRATE = ROOT / "src/powercontext/builtin/artifacts/lexical"
NOTICES = ROOT / "LICENSES/lex"


def render():
    metadata = json.loads(
        subprocess.check_output([  # noqa: S603,S607 -- fixed Cargo command and repository-owned manifest.
            "cargo",
            "metadata",
            "--locked",
            "--format-version",
            "1",
            "--manifest-path",
            str(CRATE / "Cargo.toml"),
        ])
    )
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    pending = [metadata["resolve"]["root"]]
    selected = set()
    while pending:
        package = pending.pop()
        if package in selected:
            continue
        selected.add(package)
        pending.extend(
            dependency["pkg"]
            for dependency in nodes[package]["deps"]
            if any(kind["kind"] is None for kind in dependency["dep_kinds"])
        )
    packages = [package for package in metadata["packages"] if package["id"] in selected and package["source"]]
    sections = {}
    inventory = []
    for package in sorted(packages, key=lambda package: (package["name"], package["version"])):
        name = package["name"]
        root = Path(package["manifest_path"]).parent
        files = sorted(
            path
            for path in root.rglob("*")
            if path.is_file() and path.name.upper().startswith(("LICENSE", "COPYING", "COPYRIGHT", "NOTICE"))
        )
        if name in {"jieba-rs", "jieba-macros"} and package["version"] == "0.11.0":
            files = [NOTICES / "rs-jieba.LICENSE"]
        elif name in {"include-flate-codegen", "include-flate-compress"}:
            parent = next(
                item for item in packages if item["name"] == "include-flate" and item["version"] == package["version"]
            )
            files = [Path(parent["manifest_path"]).parent / "LICENSE"]
        if not files:
            message = f"Missing upstream notice for {name} {package['version']}"
            raise SystemExit(message)
        inventory.append(f"| {name} | {package['version']} | {package['license']} |")
        for path in files:
            text = path.read_text(encoding="utf-8").strip()
            relative = path.relative_to(root).as_posix() if path.is_relative_to(root) else path.name
            label = f"{name} {package['version']}: {relative}"
            sections.setdefault(text, []).append(label)
    dictionary = (NOTICES / "py-jieba.LICENSE").read_text(encoding="utf-8").strip()
    sections.setdefault(dictionary, []).append("Python Jieba 0.42.1: embedded dict.txt")
    digest = hashlib.sha256((CRATE / "Cargo.lock").read_text(encoding="utf-8").encode()).hexdigest()
    lines = [
        "# Native lexical analyzer third-party notices",
        "",
        "Generated by `python scripts/generate_lexical_notices.py` from the locked normal dependency closure.",
        "This also includes procedural macro dependencies; build-only and development-only dependencies are excluded.",
        "Target-conditional normal dependencies are included for all supported wheel platforms.",
        "",
        f"Cargo.lock SHA-256 (UTF-8, LF): `{digest}`.",
        "",
        "The embedded Jieba dictionary is from Python Jieba 0.42.1. Its MIT notice is reproduced below.",
        "Pinned sources for notices absent from published crate archives are recorded in the adjacent source JSON files.",
        "",
        "| Crate | Version | Declared SPDX license |",
        "| --- | --- | --- |",
        *inventory,
        "",
    ]
    for index, (text, labels) in enumerate(sections.items(), 1):
        lines.extend([f"## Notice {index}", "", *[f"- {label}" for label in labels], "", "```text", text, "```", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Reject stale notices without rewriting them")
    args = parser.parse_args()
    path = NOTICES / "notice.md"
    content = render()
    if args.check:
        if path.read_text(encoding="utf-8") != content:
            message = "Lexical third-party notices are stale; run scripts/generate_lexical_notices.py"
            raise SystemExit(message)
    else:
        path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
