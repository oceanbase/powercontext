'use client';

import { useCallback, useEffect, useId, useImperativeHandle, useRef, type CSSProperties, type Ref } from 'react';
import art from '../../../figures/handoff-turntable/generated/art.json';
import '../../../figures/handoff-turntable/generated/figure.css';
import { SIDES, openingAt, sideAt, stepAt, turnAt } from '../../../figures/handoff-turntable/motion.mjs';

/** Which docking station the turntable presents the Scope tray to. */
export type HandoffSide = 'from' | 'to';

export type HandoffFigureHandle = {
  /** Plays the opening once: the turntable turns 180° from `from` to `to` while the figure grows into place. */
  play: () => Promise<void>;
  /** Turns the table to one station; resolves when it rests. */
  turnTo: (side: HandoffSide) => Promise<void>;
};

export type HandoffFigureLabels = {
  /** Accessible description of the whole figure. */
  description: string;
  /** Card chrome: figure number, title, interaction hint. The hint is also the stage's accessible name. */
  figure: string;
  title: string;
  hint: string;
  /** Live readout text per resting side. */
  readout: Record<HandoffSide, string>;
  /**
   * Names of the four Handoff steps, in loop order: Work Contract, Prepared Handoff,
   * Acknowledgement, Task Outcome. While the table turns, the readout shows the step
   * whose detent mark is under the index pawl. Without it the readout keeps the
   * destination's resting text during a turn.
   */
  steps?: readonly [string, string, string, string];
};

type Controller = { set: (values: Record<string, number>) => unknown; destroy: () => void };
type TurnRuntime = { mount: (stage: Element, data: unknown, options: Record<string, unknown>) => Controller };

type Engine = {
  controller: Controller | null;
  loading: Promise<Controller | null> | null;
  angle: number;
  side: HandoffSide;
  shown: boolean;
  opening: Promise<void> | null;
  run: number;
  frame: number;
  generation: number;
};

const prefersStill = () => typeof window !== 'undefined' && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

const STYLE = {
  '--hf-origin': `${((art.hub[0] / art.width) * 100).toFixed(3)}% ${((art.hub[1] / art.height) * 100).toFixed(3)}%`,
  '--hf-ratio': `${art.width} / ${art.height}`,
} as CSSProperties;
const VIEW_BOX = `0 0 ${art.width} ${art.height}`;
const NOSCRIPT = '<style>.hf .hf-plate{opacity:1}.hf .hf-scale{transform:none}</style>';

/**
 * The isometric handoff turntable: a rotary table (one Scope) carrying a card-file
 * box (Memory), a spindle of slips (Source journal), an in-tray (Review Inbox) and
 * the handoff cartridge, turning between the station of the session that ends and
 * the station of the next session. Static art is generated by
 * `website/figures/handoff-turntable/build.mjs`; the 3D runtime loads on the client
 * and only renders while the table turns.
 */
export function HandoffFigure({
  labels, autoplay = false, className, ref,
}: {
  labels: HandoffFigureLabels;
  /** Play the opening on mount instead of waiting for `play()`. */
  autoplay?: boolean;
  className?: string;
  ref?: Ref<HandoffFigureHandle>;
}) {
  const rootRef = useRef<HTMLDivElement>(null);
  const plateRef = useRef<HTMLDivElement>(null);
  const scaleRef = useRef<HTMLDivElement>(null);
  const readoutRef = useRef<HTMLSpanElement>(null);
  const statusRef = useRef<HTMLSpanElement>(null);
  const labelsRef = useRef(labels);
  const engine = useRef<Engine>({ controller: null, loading: null, angle: SIDES.to, side: 'to', shown: false, opening: null, run: 0, frame: 0, generation: 0 });
  const describedBy = useId();

  useEffect(() => {
    labelsRef.current = labels;
  }, [labels]);

  const draw = useCallback((angle: number) => {
    const e = engine.current;
    e.angle = angle;
    e.controller?.set({ table: angle });
    const current = labelsRef.current;
    const rest = sideAt(angle) as HandoffSide | null;
    const text = rest ? current.readout[rest] : current.steps?.[stepAt(angle)] ?? current.readout[e.side];
    const readout = readoutRef.current;
    if (readout && readout.textContent !== text) readout.textContent = text;
  }, []);

  const load = useCallback(() => {
    const e = engine.current;
    const generation = e.generation;
    e.loading ??= Promise.all([
      import('../../../figures/anatomy-kit/turn.mjs'),
      import('../../../figures/handoff-turntable/generated/turn.json'),
    ]).then(([runtime, data]) => {
      const scale = scaleRef.current;
      if (!scale || generation !== e.generation) return null;
      // The runtime samples curves by the layer's on-screen size, so measure it unscaled.
      const kept = scale.style.transform;
      scale.style.transform = 'none';
      const turn = (runtime as unknown as { TURN: TurnRuntime }).TURN;
      e.controller = turn.mount(scale, data.default ?? data, {});
      scale.style.transform = kept;
      if (!e.shown && !prefersStill()) draw(SIDES.from);
      return e.controller;
    });
    return e.loading;
  }, [draw]);

  const animate = useCallback((frameAt: (ms: number) => boolean) => {
    const e = engine.current;
    const run = ++e.run;
    cancelAnimationFrame(e.frame);
    return new Promise<boolean>((resolve) => {
      const start = performance.now();
      const tick = (now: number) => {
        if (run !== e.run) return resolve(false);
        if (frameAt(Math.max(0, now - start))) return resolve(true);
        e.frame = requestAnimationFrame(tick);
      };
      e.frame = requestAnimationFrame(tick);
    });
  }, []);

  const reveal = useCallback(() => {
    const e = engine.current;
    e.shown = true;
    if (plateRef.current) plateRef.current.style.opacity = '';
    if (scaleRef.current) scaleRef.current.style.transform = '';
    rootRef.current?.setAttribute('data-shown', '');
  }, []);

  const announce = useCallback((side: HandoffSide) => {
    if (statusRef.current) statusRef.current.textContent = labelsRef.current.readout[side];
  }, []);

  const play = useCallback(() => {
    const e = engine.current;
    e.opening ??= load().then(async (controller) => {
      if (!controller || e.shown) return;
      e.side = 'to';
      if (prefersStill()) {
        draw(SIDES.to);
        reveal();
        announce('to');
        return;
      }
      draw(SIDES.from);
      const finished = await animate((ms) => {
        const pose = openingAt(ms);
        if (plateRef.current) plateRef.current.style.opacity = String(pose.opacity);
        if (scaleRef.current) scaleRef.current.style.transform = `scale(${pose.scale})`;
        draw(pose.done ? SIDES.to : pose.angle);
        return pose.done;
      });
      if (!e.shown) {
        if (!finished) draw(e.angle);
        reveal();
      }
      if (finished) announce('to');
    });
    return e.opening;
  }, [animate, announce, draw, load, reveal]);

  const turnTo = useCallback(async (side: HandoffSide) => {
    const controller = await load();
    if (!controller) return;
    const e = engine.current;
    if (!e.shown) reveal();
    e.side = side;
    const start = e.angle;
    const end = SIDES[side];
    if (prefersStill() || start === end) {
      ++e.run;
      draw(end);
      announce(side);
      return;
    }
    const finished = await animate((ms) => {
      const pose = turnAt(ms, start, end);
      draw(pose.done ? end : pose.angle);
      return pose.done;
    });
    if (finished) announce(side);
  }, [animate, announce, draw, load, reveal]);

  useImperativeHandle(ref, () => ({ play, turnTo }), [play, turnTo]);

  useEffect(() => {
    const e = engine.current;
    if (prefersStill()) {
      e.shown = true;
      rootRef.current?.setAttribute('data-shown', '');
    }
    if (autoplay) void play();
    else void load();
  }, [autoplay, load, play]);

  useEffect(() => () => {
    const e = engine.current;
    e.run++;
    e.generation++;
    cancelAnimationFrame(e.frame);
    e.controller?.destroy();
    e.controller = null;
    e.loading = null;
    e.opening = null;
  }, []);

  const toggle = () => {
    const e = engine.current;
    if (!e.shown || !e.controller) return;
    void turnTo(e.side === 'to' ? 'from' : 'to');
  };

  return (
    <div ref={rootRef} className={['hf iso', className].filter(Boolean).join(' ')} style={STYLE}>
      <noscript dangerouslySetInnerHTML={{ __html: NOSCRIPT }} />
      <div ref={plateRef} className="hf-plate">
        <span className="hf-corner" data-corner="fig">{labels.figure}</span>
        <span className="hf-corner" data-corner="title">{labels.title}</span>
        <div
          className="hf-stage"
          role="button"
          tabIndex={0}
          aria-label={labels.hint}
          aria-describedby={describedBy}
          onClick={toggle}
          onKeyDown={(event) => {
            if (event.key !== 'Enter' && event.key !== ' ') return;
            event.preventDefault();
            toggle();
          }}
        >
          <div ref={scaleRef} className="hf-scale iso-turn">
            <svg className="iso-svg" viewBox={VIEW_BOX} aria-hidden="true" dangerouslySetInnerHTML={{ __html: art.back }} />
            <svg className="iso-svg iso-live iso-layer" data-live="table" viewBox={VIEW_BOX} aria-hidden="true" dangerouslySetInnerHTML={{ __html: art.live }} />
            <svg className="iso-svg iso-layer" viewBox={VIEW_BOX} aria-hidden="true" dangerouslySetInnerHTML={{ __html: art.front }} />
          </div>
        </div>
        <span className="hf-corner" data-corner="hint" aria-hidden="true">{labels.hint}</span>
        <span ref={readoutRef} className="hf-corner" data-corner="readout" aria-hidden="true" suppressHydrationWarning>{labels.readout.to}</span>
        <span id={describedBy} className="hf-status">{labels.description}</span>
        <span ref={statusRef} className="hf-status" aria-live="polite" />
      </div>
    </div>
  );
}
