// Builds the handoff turntable once and writes what the site renders:
//   generated/art.json   static SVG bodies (back, live table at rest, front) and layout
//   generated/turn.json  the 3D runtime's data, loaded on the client only
//   generated/figure.css kit styles scoped to `.hf` and keyed to the site's `html.dark`
//
//   node build.mjs              write the generated files
//   node build.mjs --preview    also write standalone pages (light and dark) to .preview/
//   node build.mjs --audit      run the kit audit and the orbit audit (add --quick while iterating)
//   node build.mjs --verify     preview pages carry window.__isoVerify for turn-check --order

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as k from "../anatomy-kit/iso-kit.mjs";
import * as A from "../anatomy-kit/audit.mjs";
import * as TA from "../anatomy-kit/turn-audit.mjs";
import { TURN_CSS } from "../anatomy-kit/turn.mjs";
import { BASE, buildScene, HEIGHT, HUB, P, WIDTH } from "./scene.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const has = (flag) => argv.includes(flag);
const started = Date.now();

const { R, T } = buildScene();
const SWEEP = 180;
const poses = () => Array.from({ length: SWEEP * 2 + 1 }, (_, i) => ({ table: i / 2 }));
const verify = has("--verify");
const out = T.build({ statics: R.items, poses, verify });
A.settle(R, P);

if (has("--audit")) {
  A.auditOrExit(R, P);
  TA.orbitOrExit(T, R, P, {
    sweep: { at: (x) => ({ table: x }), from: 0, to: SWEEP, frame: 0.3 },
    quick: has("--quick"),
    only: argv.find((a) => a.startsWith("--only="))?.slice(7).split(",") ?? null,
    log: has("--verbose") ? (text) => console.log(`  … ${text}`) : null,
  });
  if (process.exitCode) process.exit(process.exitCode);
}

const layerOf = (name) => R.items.filter((item) => item.layer === name).sort((a, b) => a.key - b.key).map((item) => item.svg).join("");
const back = `<path class="iso-halo" d="${k.haloOf(BASE, -17, 12, P)}"/>` + layerOf("back");
const front = layerOf("front");
const liveSvg = out.layerSvg("table", { width: WIDTH, height: HEIGHT });
const live = liveSvg.slice(liveSvg.indexOf(">") + 1, liveSvg.lastIndexOf("</svg>"));
const round2 = (n) => Math.round(n * 100) / 100;
const art = { width: WIDTH, height: HEIGHT, hub: [round2(HUB[0]), round2(HUB[1])], back, live, front };

// ---- Scoped CSS -----------------------------------------------------------
// The kit's light tokens become the default and its dark tokens follow the
// `dark` class Fumadocs puts on <html>; every other rule is scoped to `.hf`.
function rulesOf(css) {
  const rules = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}") {
      depth--;
      if (depth === 0) {
        rules.push(css.slice(start, i + 1).trim());
        start = i + 1;
      }
    }
  }
  return rules.filter(Boolean);
}
function scope(rule) {
  const open = rule.indexOf("{");
  const head = rule.slice(0, open).trim();
  const body = rule.slice(open);
  if (head.startsWith("@keyframes")) return rule;
  if (head.startsWith("@media")) return `${head}{${rulesOf(body.slice(1, -1)).map(scope).join("")}}`;
  if (head === ".iso") return `html.dark .hf.iso${body}`;
  if (head === '.iso[data-theme="light"]') return `.hf.iso${body}`;
  const selectors = head.split(",").map((s) => s.trim()).map((s) => (s.startsWith(".iso[data-theme") ? null : `.hf ${s}`)).filter(Boolean);
  return selectors.length ? `${selectors.join(",")}${body}` : "";
}
const DROP = /iso-plate|iso-legend|iso-keys|iso-key\b|iso-swatch|iso-figure|data-mat|data-hue/;
const kitRules = [...rulesOf(k.ISO_CSS), ...rulesOf(TURN_CSS)].filter((rule) => !DROP.test(rule.slice(0, rule.indexOf("{"))) && !rule.startsWith("@media (max-width"));
const FIGURE_CSS = readFileSync(join(HERE, "figure.css"), "utf8");
const css = `/* Generated by website/figures/handoff-turntable/build.mjs from the vendored Anatomy kit (MIT). Do not edit. */\n${kitRules.map(scope).filter(Boolean).join("\n")}\n${FIGURE_CSS}`;

// ---- Write ----------------------------------------------------------------
const GEN = join(HERE, "generated");
mkdirSync(GEN, { recursive: true });
const artJson = JSON.stringify(art);
const turnJson = JSON.stringify(out.data);
writeFileSync(join(GEN, "art.json"), artJson + "\n");
writeFileSync(join(GEN, "turn.json"), turnJson + "\n");
writeFileSync(join(GEN, "figure.css"), css);
const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(1)} KB`;
console.log(`art.json ${kb(artJson)} · turn.json ${kb(turnJson)} · figure.css ${kb(css)} · ${out.report.parts} live parts · ${R.items.length} static items · ${out.report.layers.map((l) => `${l.name}: ${l.planar} planar, ${l.framed ?? 0} framed, ${l.dynamic} dynamic`).join(" · ")} · ${((Date.now() - started) / 1000).toFixed(1)} s`);

// ---- Standalone preview pages ----------------------------------------------
if (has("--preview") || verify || has("--check")) {
  const PREVIEW = join(HERE, ".preview");
  mkdirSync(PREVIEW, { recursive: true });
  const strip = (file) => readFileSync(file, "utf8").replace(/^export /gm, "");
  const runtime = strip(join(HERE, "../anatomy-kit/turn.mjs"));
  const motion = strip(join(HERE, "motion.mjs"));
  const preview = readFileSync(join(HERE, "preview.js"), "utf8");
  const LABELS = {
    description: "An isometric bench instrument: a rotary table carrying a card-file box, a spindle of slips, an in-tray and a handoff cartridge turns between two docking stations.",
    figure: "Fig 1",
    title: "Handoff turntable",
    hint: "Click to hand off",
    readout: { from: "Ending session · Handoff prepared", to: "Next session · Handoff acknowledged" },
    steps: ["Work Contract", "Prepared Handoff", "Acknowledgement", "Task Outcome"],
  };
  // --check pages carry the kit's unscoped CSS, for turn-check, which re-renders layers outside `.hf`.
  const check = has("--check");
  const pageCss = check ? `${k.ISO_CSS}\n${rulesOf(TURN_CSS).filter((rule) => !DROP.test(rule)).join("\n")}\n${FIGURE_CSS}` : css;
  for (const theme of ["light", "dark"]) {
    const html = `<!doctype html><html lang="en" class="${theme === "dark" ? "dark" : ""}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Handoff turntable</title><style>${pageCss}
html,body{margin:0;background:${theme === "dark" ? "#0a0a0a" : "#fafafa"}}body{padding:40px 16px;font-family:system-ui,sans-serif}.wrap{max-width:720px;margin:0 auto}</style></head><body><div class="wrap">${check ? markup(art, LABELS).replace('class="hf iso"', `class="hf iso" data-theme="${theme}"`) : markup(art, LABELS)}</div><script type="module">${runtime}\n${motion}\nconst DATA = ${turnJson};\nconst LABELS = ${JSON.stringify(LABELS)};\n${verify ? `window.__isoVerify = ${JSON.stringify(out.verify)};\n` : ""}${preview}</script></body></html>`;
    const name = `handoff-turntable${verify ? "-verify" : ""}${check ? "-check" : ""}${theme === "light" ? "-light" : ""}.html`;
    writeFileSync(join(PREVIEW, name), html);
    console.log(`wrote .preview/${name} · ${kb(html)}`);
  }
}

/** The same markup the React component renders, as a string. */
function markup(a, labels) {
  const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/"/g, "&quot;");
  const vb = `0 0 ${a.width} ${a.height}`;
  const origin = `${((a.hub[0] / a.width) * 100).toFixed(3)}% ${((a.hub[1] / a.height) * 100).toFixed(3)}%`;
  return `<div class="hf iso" style="--hf-origin:${origin};--hf-ratio:${a.width}/${a.height}"><div class="hf-plate"><div class="hf-body"><span class="hf-corner" data-corner="title"><span>${esc(labels.figure)}</span><span>${esc(labels.title)}</span></span><div class="hf-stage" role="button" tabindex="0" aria-label="${esc(labels.hint)}"><div class="hf-scale iso-turn"><svg xmlns="http://www.w3.org/2000/svg" class="iso-svg" viewBox="${vb}" aria-hidden="true">${a.back}</svg><svg xmlns="http://www.w3.org/2000/svg" class="iso-svg iso-live iso-layer" data-live="table" viewBox="${vb}" aria-hidden="true">${a.live}</svg><svg xmlns="http://www.w3.org/2000/svg" class="iso-svg iso-layer" viewBox="${vb}" aria-hidden="true">${a.front}</svg></div></div><span class="hf-corner" data-corner="status" aria-hidden="true"><span data-hint>${esc(labels.hint)}</span><span data-readout>${esc(labels.readout.to)}</span></span></div><span class="hf-status">${esc(labels.description)}</span><span class="hf-status" aria-live="polite"></span></div></div>`;
}
