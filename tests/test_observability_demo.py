"""Configuration generated by the documented reference demo entrypoint."""

from __future__ import annotations

import runpy
import shutil
from pathlib import Path

import pytest

from powercontext.env_file import environment_context, read_environment_file
from powercontext.server.settings import ServerSettings


@pytest.mark.skipif(shutil.which("openssl") is None, reason="reference demo requires OpenSSL")
def test_reference_demo_enables_log_export_and_preserves_configuration(tmp_path, monkeypatch):
    script = tmp_path / "demo with spaces" / "init.py"
    script.parent.mkdir()
    shutil.copyfile(Path(__file__).resolve().parents[1] / "deploy/observability/init.py", script)
    monkeypatch.setattr("sys.argv", [str(script)])
    runpy.run_path(str(script), run_name="__main__")

    environment = script.parent / ".local" / "server.env"
    with environment_context(read_environment_file(environment), override=True):
        settings = ServerSettings()
    assert settings.tracing.enabled
    assert settings.logging.otlp_enabled
    assert settings.logging.format == "json"
    assert read_environment_file(environment)["OTEL_RESOURCE_ATTRIBUTES"] == (
        "powercontext.service.api_target=host.docker.internal:18080"
    )
    original = environment.read_bytes()
    token = environment.parent / "observe-token"
    original_token = token.read_bytes()
    runpy.run_path(str(script), run_name="__main__")
    assert environment.read_bytes() == original
    assert token.read_bytes() == original_token
