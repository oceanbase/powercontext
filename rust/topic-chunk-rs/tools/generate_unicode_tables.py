"""Generate Python Unicode16 classifications used by the independent Rust scanner."""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import unicodedata
from pathlib import Path


def ranges(values: list[int]) -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    for value in values:
        if result and value == result[-1][1] + 1:
            result[-1] = (result[-1][0], value)
        else:
            result.append((value, value))
    return result


def render() -> str:
    if sys.version_info[:2] != (3, 14) or unicodedata.unidata_version != "16.0.0":
        message = "Generation requires CPython 3.14 and Unicode 16.0.0"
        raise RuntimeError(message)
    source = Path(__file__).read_bytes()
    header = source.decode().split('"""', 1)[0].replace("#", "//")
    groups = {
        "SPACE": [cp for cp in range(0x110000) if chr(cp).isspace()],
        "DIGIT": [cp for cp in range(0x110000) if re.fullmatch(r"\d", chr(cp))],
    }
    text = header + "// Generated by tools/generate_unicode_tables.py; do not edit.\n"
    text += f"// Generator SHA-256: {hashlib.sha256(source).hexdigest()}\n"
    text += f"// CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.\n\n"
    for name, values in groups.items():
        text += f"pub const {name}: &[(u32, u32)] = &[\n"
        text += "".join(f"    (0x{start:X}, 0x{end:X}),\n" for start, end in ranges(values))
        text += "];\n\n"
    return text.rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / "src" / "unicode_tables.rs"
    generated = render()
    if args.check:
        if path.read_text() != generated:
            message = "Unicode tables differ from target interpreter"
            raise RuntimeError(message)
    else:
        path.write_text(generated)


if __name__ == "__main__":
    main()
